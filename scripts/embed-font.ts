/**
 * Writes src/render/font.ts: the two display faces (Latin subsets) as base64, so
 * reports and cards get them without any download at run time.
 *
 * - Space Grotesk Bold: headlines and big numbers in the report and stats cards
 * - Anton: the condensed poster headlines
 *
 *   node scripts/embed-font.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

interface Face {
  pkg: string;
  file: string;
  /** The weights the face is declared for; a range stops browsers faking a bold. */
  weight: string;
}

const FACES: Record<'display' | 'headline', Face> = {
  display: { pkg: 'space-grotesk', file: 'space-grotesk-latin-700-normal.woff2', weight: '700' },
  headline: { pkg: 'anton', file: 'anton-latin-400-normal.woff2', weight: '400 900' },
};

const dir = (pkg: string): string => fileURLToPath(new URL(`../node_modules/@fontsource/${pkg}/`, import.meta.url));
const base64 = (face: Face): string => readFileSync(`${dir(face.pkg)}files/${face.file}`).toString('base64');
// The SIL Open Font License asks for its text to travel with the font.
const license = (face: Face): string =>
  readFileSync(`${dir(face.pkg)}LICENSE`, 'utf8').trim().replace(/\*\//g, '* /').split('\n').map((line) => ` * ${line}`.trimEnd()).join('\n');

const display = base64(FACES.display);
const headline = base64(FACES.headline);

const out = `// Generated by scripts/embed-font.ts. Do not edit by hand.

/*
 * Space Grotesk Bold, Latin subset, via @fontsource/space-grotesk.
 *
${license(FACES.display)}
 */

/*
 * Anton, Latin subset, via @fontsource/anton.
 *
${license(FACES.headline)}
 */

export const DISPLAY_FAMILY = 'Commitale Display';
export const HEADLINE_FAMILY = 'Commitale Headline';

const DISPLAY_WOFF2 = '${display}';
const HEADLINE_WOFF2 = '${headline}';

/** @font-face rules carrying both faces inline, for pages and standalone SVG files. */
export const FONT_FACE =
  \`@font-face{font-family:'\${DISPLAY_FAMILY}';src:url(data:font/woff2;base64,\${DISPLAY_WOFF2}) format('woff2');font-weight:${FACES.display.weight};font-display:block}\` +
  \`@font-face{font-family:'\${HEADLINE_FAMILY}';src:url(data:font/woff2;base64,\${HEADLINE_WOFF2}) format('woff2');font-weight:${FACES.headline.weight};font-display:block}\`;
`;

writeFileSync(fileURLToPath(new URL('../src/render/font.ts', import.meta.url)), out);
console.log(`Wrote src/render/font.ts (${Math.round((display.length + headline.length) / 1024)} KB of base64)`);
