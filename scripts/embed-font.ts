/**
 * Writes src/render/font.ts: Space Grotesk Bold (Latin subset) as base64, so reports
 * and cards get the display face without any download at run time.
 *
 *   node scripts/embed-font.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../node_modules/@fontsource/space-grotesk/', import.meta.url));
const woff2 = readFileSync(`${dir}files/space-grotesk-latin-700-normal.woff2`).toString('base64');
// The SIL Open Font License asks for its text to travel with the font.
const license = readFileSync(`${dir}LICENSE`, 'utf8').trim().replace(/\*\//g, '* /');

const out = `// Generated by scripts/embed-font.ts. Do not edit by hand.

/*
 * Space Grotesk Bold, Latin subset, via @fontsource/space-grotesk.
 *
${license.split('\n').map((line) => ` * ${line}`.trimEnd()).join('\n')}
 */

export const DISPLAY_FAMILY = 'Commitale Display';

const WOFF2 = '${woff2}';

/** An @font-face rule carrying the font inline, for pages and standalone SVG files. */
export const FONT_FACE = \`@font-face{font-family:'\${DISPLAY_FAMILY}';src:url(data:font/woff2;base64,\${WOFF2}) format('woff2');font-weight:700;font-display:block}\`;
`;

writeFileSync(fileURLToPath(new URL('../src/render/font.ts', import.meta.url)), out);
console.log(`Wrote src/render/font.ts (${Math.round(woff2.length / 1024)} KB of base64)`);
